/**
 * BreatheWise entry point: the plan-generation flow (live data → GenAI plan →
 * render) plus wiring for the location, impact and chat controllers.
 * @module app
 */
import { categorize, cigaretteEquivalent, bestWindows, summarizeForecast } from './aqi.js';
import { validateProfile } from './validate.js';
import { fetchConditions, askModel } from './api.js';
import { buildPlanMessages, parsePlan } from './plan.js';
import { buildOfflinePlan } from './offline-plan.js';
import { el, renderForecastChart, renderPlanItems } from './ui.js';
import { formatHour, addHours, formatMeasure } from './format.js';
import { byId, buttonById, formById, setStatus, scrollBehavior, errorMessage } from './dom.js';
import { state } from './state.js';
import { initLocation, ensurePlace } from './location.js';
import { initImpactCalculator, syncImpactDefaults } from './impact-calculator.js';
import { initChat, resetChat, readGeminiKey } from './chat.js';
import { FORECAST } from './config.js';

/** Checkbox fields of the household form. */
const FLAGS = Object.freeze(['children', 'elderly', 'respiratory', 'pets', 'purifier']);
/** Free-value fields of the household form. */
const FIELDS = Object.freeze(['size', 'commuteMode', 'commuteKm', 'windows', 'exercise', 'cooking', 'notes']);

/**
 * Read the household form into a validated profile.
 * @returns {import('./validate.js').Profile}
 */
function readProfile() {
  const data = new FormData(formById('profile-form'));
  /** @type {Record<string, unknown>} */
  const raw = {};
  for (const name of FLAGS) raw[name] = data.has(name);
  for (const name of FIELDS) raw[name] = data.get(name);
  return validateProfile(raw);
}

/**
 * One-line forecast summary, with a smog warning when the wind is low.
 * @param {ReturnType<typeof summarizeForecast>} forecast
 * @param {number|undefined} wind km/h
 * @returns {string}
 */
export function describeForecast(forecast, wind) {
  if (forecast.points.length === 0) return 'Hourly forecast unavailable.';
  const lowWind = wind != null && wind < FORECAST.lowWindKmh ? ' Low wind means smog can build up.' : '';
  return `AQI will range from ${forecast.min} to ${forecast.max}, peaking around ${formatHour(forecast.peakTime)}.${lowWind}`;
}

/**
 * Render the AQI badge, pollutant list and cigarette equivalent.
 * @param {import('./plan.js').PlanContext} ctx
 */
function renderCurrentAir(ctx) {
  const cat = categorize(ctx.air.aqi);
  const badge = byId('aqi-badge');
  byId('aqi-value').textContent = String(ctx.air.aqi);
  byId('aqi-label').textContent = cat.label;
  badge.style.setProperty('--aqi-color', cat.color);
  badge.dataset.level = cat.level;
  byId('aqi-advice').textContent = `${ctx.place}: ${cat.advice}`;
  const rows = [
    ['PM2.5', formatMeasure(ctx.air.pm25, 'µg/m³')],
    ['PM10', formatMeasure(ctx.air.pm10, 'µg/m³')],
    ['NO₂', formatMeasure(ctx.air.no2, 'µg/m³')],
    ['Ozone', formatMeasure(ctx.air.o3, 'µg/m³')],
    ['Wind', formatMeasure(ctx.weather?.wind, 'km/h')],
    ['Temp', formatMeasure(ctx.weather?.temperature, '°C')],
  ];
  byId('pollutants').replaceChildren(
    ...rows.flatMap(([term, value]) => [el('dt', {}, [term]), el('dd', {}, [value])]),
  );
  byId('cigarette').textContent =
    `Breathing this air all day is like smoking about ${cigaretteEquivalent(ctx.air.pm25)} cigarettes.`;
}

/**
 * Render the 24h chart summary and the cleanest outdoor windows.
 * @param {import('./plan.js').PlanContext} ctx
 * @param {ReturnType<typeof summarizeForecast>} forecast
 */
function renderForecast(ctx, forecast) {
  byId('forecast-summary').textContent = describeForecast(forecast, ctx.weather?.wind);
  renderForecastChart(byId('forecast-chart'), forecast.points);
  const items = ctx.forecast.best.map((w, i) =>
    el('li', {}, [
      el('strong', {}, [i === 0 ? 'Best time outdoors: ' : 'Next best: ']),
      `${formatHour(w.start)} – ${formatHour(addHours(w.end, 1))} (avg AQI ${w.average}, ${categorize(w.average).label})`,
    ]),
  );
  byId('best-windows').replaceChildren(
    ...(items.length ? items : [el('li', {}, ['No clean daytime window today — keep outdoor time short.'])]),
  );
}

/**
 * Render the three plan sections and where the plan came from.
 * @param {import('./plan.js').Plan} plan
 * @param {string} provider
 */
function renderPlan(plan, provider) {
  byId('plan-summary').textContent = plan.summary;
  byId('plan-source').textContent =
    plan.source === 'ai' ? `Generated by ${provider}` : 'Offline expert rules (AI unavailable)';
  renderPlanItems(byId('plan-routine'), plan.routine);
  renderPlanItems(byId('plan-indoor'), plan.indoor);
  renderPlanItems(byId('plan-alternatives'), plan.alternatives);
}

/**
 * Fetch live data and build the grounded plan context.
 * @param {import('./state.js').Place} place
 * @param {import('./validate.js').Profile} profile
 * @returns {Promise<{ctx: import('./plan.js').PlanContext, forecast: ReturnType<typeof summarizeForecast>}>}
 */
async function loadContext(place, profile) {
  const data = await fetchConditions(place.lat, place.lon);
  const forecast = summarizeForecast(data.hourly.time, data.hourly.aqi, FORECAST.hours);
  const best = bestWindows(
    forecast.points.map((p) => p.time),
    forecast.points.map((p) => p.aqi),
    {
      length: FORECAST.windowHours,
      limit: FORECAST.windows,
      startHour: FORECAST.dayStartHour,
      endHour: FORECAST.dayEndHour,
    },
  );
  const ctx = {
    place: place.name,
    air: data.air,
    weather: data.weather,
    forecast: { min: forecast.min, max: forecast.max, peakTime: forecast.peakTime, best },
    profile,
  };
  return { ctx, forecast };
}

/**
 * Ask the model for a plan; fall back to the offline rules on any failure.
 * @param {import('./plan.js').PlanContext} ctx
 * @returns {Promise<{plan: import('./plan.js').Plan, provider: string}>}
 */
async function requestPlan(ctx) {
  try {
    const res = await askModel(buildPlanMessages(ctx), { geminiKey: readGeminiKey() });
    const plan = parsePlan(res.text);
    if (plan) return { plan, provider: res.provider };
  } catch (err) {
    console.warn('AI request failed, using offline plan:', errorMessage(err));
  }
  return { plan: buildOfflinePlan(ctx), provider: 'offline rules' };
}

/**
 * Toggle the busy state of the plan generator (button + aria-busy).
 * @param {boolean} busy
 */
function setBusy(busy) {
  state.busy = busy;
  buttonById('generate-btn').disabled = busy;
  byId('plan-section').setAttribute('aria-busy', String(busy));
}

/**
 * Live data → render conditions → GenAI plan → render plan.
 * @param {import('./state.js').Place} place
 */
async function runPlanFlow(place) {
  setStatus('Fetching live air quality…');
  const profile = readProfile();
  const { ctx, forecast } = await loadContext(place, profile);
  state.context = ctx;
  byId('results').hidden = false;
  renderCurrentAir(ctx);
  renderForecast(ctx, forecast);
  syncImpactDefaults(profile);

  setStatus('Asking the AI for your personalised plan…');
  const { plan, provider } = await requestPlan(ctx);
  state.plan = plan;
  resetChat();
  renderPlan(plan, provider);
  setStatus(
    plan.source === 'ai'
      ? 'Your plan is ready.'
      : 'Your plan is ready (generated offline because the AI service was unavailable).',
    'success',
  );
  byId('air-title').scrollIntoView({ behavior: scrollBehavior() });
}

/**
 * Form submit handler.
 * @param {SubmitEvent} event
 */
async function generatePlan(event) {
  event.preventDefault();
  if (state.busy || !(await ensurePlace()) || !state.place) return;
  setBusy(true);
  try {
    await runPlanFlow(state.place);
  } catch (err) {
    setStatus(`Something went wrong: ${errorMessage(err)}`, 'error');
  } finally {
    setBusy(false);
  }
}

/** Wire up every controller once the module loads. */
function init() {
  formById('profile-form').addEventListener('submit', generatePlan);
  initLocation();
  initImpactCalculator();
  initChat();
}

if (typeof document !== 'undefined') init();
